const PG_TABLES = ["users", "complaints", "votes", "resolve_requests", "moderation_log", "geo_cache"];

let sqlite;
let sql;
let driver = null;
let opening = null;
let readyDone = false;
let moderatorCreated = false;
let queue = Promise.resolve();

loadEnvFile();

function loadEnvFile() {
  if (process.env.NODE_TEST_CONTEXT) return;
  const file = path.join(__dirname, "..", ".env");
  if (!fs.existsSync(file)) return;
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq < 1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined) process.env[key] = value;
  }
}

function databaseUrl() {
  return process.env.DATABASE_URL || process.env.SUPABASE_DB_URL || "";
}

function usesSupabase() {
  return Boolean(databaseUrl());
}

function schedule(fn) {
  const run = queue.then(fn, fn);
  queue = run.then(() => {}, () => {});
  return run;
}

function placeholders(text) {
  let index = 0;
  return text.replace(/\?/g, () => {
    index += 1;
    return `$${index}`;
  });
}

function withReturning(text) {
  const trimmed = text.trim().replace(/;\s*$/, "");
  if (!/^insert\s+into\s+(users|complaints|votes|moderation_log)\b/i.test(trimmed)) return trimmed;
  if (/\breturning\b/i.test(trimmed)) return trimmed;
  return `${trimmed} RETURNING id`;
}

function normalize(row) {
  if (!row || typeof row !== "object") return row;
  const copy = { ...row };
  for (const key of Object.keys(copy)) {
    if (copy[key] == null || !NUMERIC.has(key) || typeof copy[key] === "number") continue;
    const number = Number(copy[key]);
    if (Number.isFinite(number)) copy[key] = number;
  }
  return copy;
}

async function raw(client, text, params, method) {
  if (driver === "pg") {
    const query = method === "run" ? withReturning(placeholders(text)) : placeholders(text);
    const rows = await (client || sql).unsafe(query, params);
    const list = [...rows].map(normalize);
    if (method === "all") return list;
    if (method === "get") return list[0];
    return { lastInsertRowid: list[0]?.id ?? 0, changes: rows.count ?? 0 };
  }
  const stmt = sqlite.prepare(text);
  if (method === "all") return stmt.all(...params);
  if (method === "get") return stmt.get(...params);
  return stmt.run(...params);
}

async function exec(client, text, params, method) {
  if (!readyDone) await ready();
  return raw(client, text, params, method);
}

function facade(client, direct) {
  return {
    prepare(text) {
      const run = (method, params) => {
        const job = () => (direct ? raw(client, text, params, method) : exec(client, text, params, method));
        return direct ? job() : schedule(job);
      };
      return {
        get: (...params) => run("get", params),
        all: (...params) => run("all", params),
        run: (...params) => run("run", params),
      };
    },
  };
}

async function seedModerator() {
  const existing = await raw(null, "SELECT id FROM users WHERE username = ?", ["moderador"], "get");
  if (existing) return false;
  await raw(
    null,
    `INSERT INTO users (username, password_hash, role, created_at) VALUES (?, ?, 'moderator', ?)`,
    ["moderador", bcrypt.hashSync("Pueblo2026!", 10), new Date().toISOString()],
    "run"
  );
  moderatorCreated = true;
  return true;
}

