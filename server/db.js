async function openPostgres() {
  sql = postgres(databaseUrl(), {
    ssl: "require",
    max: ON_VERCEL ? 1 : 3,
    idle_timeout: 20,
    connect_timeout: 15,
    prepare: false,
  });
  try {
    for (const statement of PG_SCHEMA) await sql.unsafe(statement);
    for (const table of PG_TABLES) {
      await sql.unsafe(`ALTER TABLE ${table} ENABLE ROW LEVEL SECURITY`);
      try {
        await sql.unsafe(`REVOKE ALL ON TABLE ${table} FROM anon, authenticated`);
      } catch {
        /* Fuera de Supabase esos roles no existen. */
      }
    }
    driver = "pg";
    await seedModerator();
  } catch (error) {
    driver = null;
    const ending = sql;
    sql = null;
    await ending.end({ timeout: 1 }).catch(() => {});
    throw error;
  }
}

async function open() {
  if (usesSupabase()) await openPostgres();
  else {
    openSqlite();
    await seedModerator();
  }
}

function ready() {
  if (readyDone) return Promise.resolve();
  if (!opening) {
    opening = open()
      .then(() => {
        readyDone = true;
      })
      .catch((error) => {
        opening = null;
        throw error;
      });
  }
  return opening;
}

function getDb() {
  return facade(null, false);
}

function transaction(fn) {
  return schedule(async () => {
    await ready();
    if (driver === "pg") return sql.begin(async (tx) => fn(facade(tx, true)));
    sqlite.exec("BEGIN IMMEDIATE");
    try {
      const result = await fn(facade(null, true));
      sqlite.exec("COMMIT");
      return result;
    } catch (error) {
      sqlite.exec("ROLLBACK");
      throw error;
    }
  });
}

async function runRaw(statement) {
  await ready();
  if (driver !== "pg") throw new Error("Esta operación solo está disponible con Supabase.");
  return sql.unsafe(statement);
}

async function close() {
  await queue.catch(() => {});
  readyDone = false;
  opening = null;
  moderatorCreated = false;
  driver = null;
  if (sqlite) {
    sqlite.close();
    sqlite = null;
  }
  if (sql) {
    const ending = sql;
    sql = null;
    await ending.end({ timeout: 5 });
  }
}

function secret() {
  if (process.env.SECRET) return process.env.SECRET;
  const file = path.join(RUNTIME, "secret.txt");
  try {
    if (fs.existsSync(file)) return fs.readFileSync(file, "utf8").trim();
    fs.mkdirSync(path.dirname(file), { recursive: true });
    const value = crypto.randomBytes(32).toString("hex");
    fs.writeFileSync(file, value);
    return value;
  } catch {
    return "eptlo-vercel";
  }
}

